"""tests/unit conftest — the ordering guard for the celery suite's shared fixtures (R20 item 3).

WHY this file exists (mechanism read off pytest 9.1.1, measured in raw/probe3_ABC.txt)
---------------------------------------------------------------------------------------
pytest 9.1.1 parses a conftest's fixtures exactly ONCE, against the FIRST Directory/Package
collector created for that conftest's directory: `FixtureManager.pytest_plugin_registered`
parks the conftest in `_pending_conftests[dir]` and the `pytest_make_collect_report` wrapper
pops it and calls `parsefactories(holder=plugin, node=<that node>)`.  Fixture visibility is
NODE IDENTITY — `_matchfactories` keeps only defs with `fixturedef.node in set(node.iter_parents())`.

A mixed FILE-argument battery can therefore lose them: collecting a file arg re-collects its
parent directory with `handle_dupes=False`, which regenerates that directory's child collectors;
when a later arg walks through the regenerated child, its items are parented onto a SECOND
Package node instance for the same path — one that never received the deferred parse.  Measured:
`pytest tests/unit/celery/test_agent_tasks.py tests/unit/test_policy_firewall.py
tests/unit/celery/test_queue_safety_core.py -q` collected the `tests/unit/celery` Package twice
(`…012752` got `queue_db`; the later file's items sat under `…900864`) -> 34 passed then
8x "fixture 'queue_db' not found".  Directory-recursion runs (the full suite) and the
celery->celery / celery->other / other->celery orders stayed green.

WHY re-exposing here is correct
-------------------------------
The `tests/unit` Package node is NOT regenerated by file-argument batteries (only a file arg
directly in `tests/` would re-collect it, and `tests/` holds no test files — `ls tests/*.py`
is `__init__.py` + `conftest.py`), so fixtures defined on this node are visible to every item
below it in ANY argument order.  The celery conftest stays authoritative: these are the same
fixture objects (imported, not copied), and when both defs are visible the closer celery
definition still wins.  Residual, recorded rather than hidden: a future test FILE placed
directly under `tests/` could move the duplicated node one level up — extend this guard then.

`quiet_redis` is re-defined (guarded, not imported): its job is "no network under
tests/unit/celery", and re-exposing it unguarded would silently make it autouse for ALL of
tests/unit.  The guard keeps it inert outside the celery directory; inside, it behaves exactly
like the celery conftest's copy (same mock shape, same monkeypatch seam).
"""
from __future__ import annotations

from pathlib import Path
from unittest.mock import AsyncMock

import pytest

# Same fixture OBJECTS as tests/unit/celery/conftest.py (import, not copy — keep single-source).
from tests.unit.celery.conftest import (  # noqa: F401
    eager_delivery,
    execute_body,
    install_run_spy,
    queue_db,
    service,
    steal_claim,
    worker_fn,
)

CELERY_DIR = Path(__file__).resolve().parent / "celery"


def _is_under_celery_dir(path: Path | str) -> bool:
    """True when `path` lives under tests/unit/celery/ — the scope the no-network mock serves."""
    try:
        return Path(path).resolve().is_relative_to(CELERY_DIR)
    except OSError:  # pragma: no cover - unreadable path: stay inert rather than fail a test
        return False


@pytest.fixture(autouse=True)
def quiet_redis(request, monkeypatch):
    """The celery suite's autouse no-network fixture, made order-independent (R20 item 3).

    Inert for every test outside tests/unit/celery/; inside, the real publish seam is mocked so
    the first publish does not pay the refused-Redis-socket retry ladder (see the celery
    conftest's copy for the full rationale).
    """
    if not _is_under_celery_dir(request.path):
        return None
    mock = AsyncMock()
    mock.publish = AsyncMock(return_value=1)
    monkeypatch.setattr("app.core.events.get_redis", lambda: mock)
    return mock
